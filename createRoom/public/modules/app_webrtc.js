// handle a closure
export function closePeerConnection() {

    // step 1 (optional): close a data channel if it exists
    if(dataChannel) {
        dataChannel.close();
        dataChannel = null;
        console.log("data channel closed");
    }

    // step 2: close the pc if it exists
    if(pc) {
        pc.close(); // calling this will automatically close all data channels
        pc = null; // ensure we free up memory by setting pc object to null
        dataChannel = null;
        console.log("You have closed your peer connection by calling the 'close()' method");
    }

    console.log("Your pc object after calling closePeerConnection() is : ", pc);
};

function createDataChannel(isOfferer) {

    if (isOfferer) {

        const dataChannelOption = {
            ordered: false,
            maxRetransmits: 0
        }

        dataChannel = pc.createDataChannel("unique-chat-room", dataChannelOption)

        registerDataChannelListener();
        logToConsole(`Successfully create a Data channel and added to PC `)

    } else {

        pc.ondatachannel = (event) => {
            console.log("The ondatachannel event was emitted for PEER2. Here is the event object: ", event);
            dataChannel = event.channel;
            registerDataChannelListener();
            logToConsole(`Successfully registered a Data channel and added to PC `)
        }

    }
}


