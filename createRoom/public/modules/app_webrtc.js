async function handleVideoOffer(data) {
    try {
        if (!pc) createPeerConnectionObject();

        logToConsole("Remote video received. Tap Start Video Call to share your camera too.", appconstants.theme.orange);

        const firstNewIceCandidate = iceCandidatesGenerated.length;
        await pc.setRemoteDescription(data.offer);
        const answer = await pc.createAnswer();
        await pc.setLocalDescription(answer);
        await waitForIceGatheringComplete();

        uiUtils.showVideoUI();
        clientWebsocket.sendAnswer(pc.localDescription, true);
        logToConsole("Video offer received. Video answer sent.", appconstants.theme.green);

        const newCandidates = iceCandidatesGenerated.slice(firstNewIceCandidate);
        if (newCandidates.length > 0) clientWebsocket.sendIceCandidates(newCandidates);
    } catch (error) {
        console.error("Unable to accept video offer", error);
        logToConsole(`Unable to accept video offer: ${error.message}`, appconstants.theme.red);
    }
}

export function handleAnswer(data) {
    if (data.isVideoAnswer) {
        handleVideoAnswer(data);
        return;
    }

    uiUtils.logToConsole("answer received. Send your ice candidates to PEER2");
    // show the ice button
    DOM.offerorIceButton.classList.remove("hide");
    DOM.offerorIceButton.classList.add("show-ice");

    DOM.offerorIceButton.addEventListener("click", () => {
        clientWebsocket.sendIceCandidates(iceCandidatesGenerated);
        // ui changes
        uiUtils.updateUIButton(DOM.offerorIceButton, "Finally, set your remote description");
        // show the setRemoteDescriptionButton
        DOM.offerorSetRemoteDescriptionButton.classList.remove("hide");
    });

    DOM.offerorSetRemoteDescriptionButton.addEventListener("click", async () => {
        await pc.setRemoteDescription(data.answer);
        uiUtils.logToConsole("remote description updated with the answer");

        // finally, add the ice candidates inside the buffer (if any)
        // once remoteDescription is set, you can add ice candidates
        for (const candidate of iceCandidatesReceivedBuffer) {
            await pc.addIceCandidate(candidate);
            uiUtils.logToConsole('Added ice candidate to pc');
        }

        iceCandidatesReceivedBuffer.splice(0, iceCandidatesReceivedBuffer.length); // reset buffer
    });


};

async function handleVideoAnswer(data) {
    try {
        await pc.setRemoteDescription(data.answer);
        logToConsole("Video answer received. Video connection is ready.", appconstants.theme.green);
    } catch (error) {
        console.error("Unable to accept video answer", error);
        logToConsole(`Unable to accept video answer: ${error.message}`, appconstants.theme.red);
    }
}
export function handleIceCandidates(data) {
    if(pc.remoteDescription) {
        try {
            data.candidatesArray.forEach(candidate => {
                pc.addIceCandidate(candidate);
                uiUtils.logToConsole("Added ice candidate to your pc object");
            });
        } catch (error) {
            console.log("Error trying to add an ice candidate to the pc object", error);
        }
    } else {
        // create a temporary buffer
        data.candidatesArray.forEach(candidate => {
            iceCandidatesReceivedBuffer.push(candidate);
            uiUtils.logToConsole("Added ice candidate to your temp buffer");
        })
    }
}; // end of the handleIceCandidates function


